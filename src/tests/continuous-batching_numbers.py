# ---------- constants from the config and the datasheet ----------
LAYERS, H, FFN, VOCAB, POS = 40, 5120, 20480, 50272, 2048
attn = 4 * (H * H + H)                    # q, k, v, out_proj with biases
mlp = (H * FFN + FFN) + (FFN * H + H)     # fc1, fc2 with biases
norms = 2 * (2 * H)                       # two LayerNorms per layer
PARAMS = LAYERS * (attn + mlp + norms) + VOCAB * H + (POS + 2) * H + 2 * H   # + embeddings, learned positions (offset 2), final norm
W_BYTES = 2 * PARAMS                      # float16
KV_TOK = 2 * LAYERS * H * 2               # K and V, every layer, 2 bytes
BW, PEAK = 1555e9, 312e12
GiB = 2 ** 30
BUDGET = 40 * GiB * 0.92 - W_BYTES - 2 * GiB
AVG = 512 + 128
B_MAX = int(BUDGET // (KV_TOK * AVG))
TW = W_BYTES / BW
def tc(eff): return 2 * PARAMS / (PEAK * eff / 100)
def step(ntok, kvtok, eff): return max(TW, ntok * tc(eff)) + kvtok * KV_TOK / BW

# ---------- workload: mulberry32 + inverse CDF of the capped exponential ----------
def mulberry32(a):
    a &= 0xFFFFFFFF
    def nxt():
        nonlocal a
        a = (a + 0x6D2B79F5) & 0xFFFFFFFF
        t = ((a ^ (a >> 15)) * (a | 1)) & 0xFFFFFFFF
        t = (t + (((t ^ (t >> 7)) * (t | 61)) & 0xFFFFFFFF)) & 0xFFFFFFFF ^ t
        return ((t ^ (t >> 14)) & 0xFFFFFFFF) / 2 ** 32
    return nxt
SEEDS = [132, 45, 123]
def workload(st, cap, rate):
    r = mulberry32(SEEDS[st]); q = 1 - math.exp(-cap / 128)
    lens = [max(1, math.ceil(-128 * math.log(1 - r() * q))) for _ in range(48)]
    arr = [0.0] * 48
    if rate > 0:
        g = mulberry32(SEEDS[st] + 7919)
        for i in range(1, 48): arr[i] = arr[i - 1] - math.log(1 - g()) / rate
    return lens, arr

# ---------- simulator (independent formulation) ----------
ENDS = []                                  # end time of every step of the last simulated run
JN = []                                    # prompts prefilled in each of those steps
def sim_static(B, lens, arr, eff):
    n = len(lens); start = [0.0] * n; first = [0.0] * n; fin = [0.0] * n; peak = 0; ENDS.clear(); JN.clear()
    t = 0.0; nxt = 0; queue = []
    while nxt < n or queue:
        while nxt < n and arr[nxt] <= t + 1e-12: queue.append(nxt); nxt += 1
        if not queue: t = arr[nxt]; continue
        batch, queue = queue[:B], queue[B:]
        for i in batch: start[i] = t
        t += step(512 * len(batch), 0, eff); peak = max(peak, len(batch) * 513); ENDS.append(t); JN.append(len(batch))
        for i in batch:
            first[i] = t
            if lens[i] == 1: fin[i] = t
        for k in range(1, max(lens[i] for i in batch)):   # decode step k: requests holding k tokens that need more
            act = [i for i in batch if lens[i] > k]
            kv = sum(512 + k for _ in act); peak = max(peak, kv + len(act))
            t += step(len(act), kv, eff); ENDS.append(t); JN.append(0)
            for i in act:
                if lens[i] == k + 1: fin[i] = t
    return start, first, fin, peak

def sim_cont(B, lens, arr, eff):
    n = len(lens); start = [0.0] * n; first = [0.0] * n; fin = [0.0] * n
    have = [0] * n; slot_of = [None] * n; slots = [None] * B; peak = 0; ENDS.clear(); JN.clear()
    t = 0.0; nxt = 0; queue = []
    while nxt < n or queue or any(s is not None for s in slots):
        while nxt < n and arr[nxt] <= t + 1e-12: queue.append(nxt); nxt += 1
        if not queue and all(s is None for s in slots): t = arr[nxt]; continue
        joined = []
        for j in range(B):
            if slots[j] is None and queue:
                i = queue.pop(0); slots[j] = i; start[i] = t; joined.append(i)
        dec = [i for i in slots if i is not None and i not in joined]
        kv = sum(512 + have[i] for i in dec)
        peak = max(peak, kv + len(dec) + 513 * len(joined))
        t += step(len(dec) + 512 * len(joined), kv, eff); ENDS.append(t); JN.append(len(joined))
        for j in range(B):
            i = slots[j]
            if i is None: continue
            have[i] += 1
            if have[i] == 1: first[i] = t
            if have[i] == lens[i]: fin[i] = t; slots[j] = None
    return start, first, fin, peak

def metrics(pol, B, st, cap, rate, eff):
    lens, arr = workload(st, cap, rate)
    start, first, fin, peak = (sim_cont if pol == 'cont' else sim_static)(B, lens, arr, eff)
    mk = max(fin); tok = sum(lens); busy = sum(f - s for f, s in zip(fin, start))
    lat = sorted(f - a for f, a in zip(fin, arr))
    tp = [(fin[i] - first[i]) / (lens[i] - 1) for i in range(48) if lens[i] > 1]
    return dict(mk=mk, thr=tok / mk, util=busy / (B * mk), mlat=sum(lat) / 48, p90=lat[math.ceil(0.9 * 48) - 1],
                tpot=sum(tp) / len(tp), tokens=tok, busy=busy, peak=peak, start=start, fin=fin, lens=lens)

def teaser():
    L, B = [4, 11, 2, 6, 3, 8, 5, 2, 9, 3], 4
    s = sum(max(L[k:k + B]) for k in range(0, len(L), B))
    free = [0] * B; q = list(L)          # continuous: each slot is free again at the step its request ends
    for x in q: j = free.index(min(free)); free[j] += x
    c = max(free)
    return s, sum(L) / (B * s), c, sum(L) / (B * c)

