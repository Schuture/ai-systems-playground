def pace_w(p_, p0):                               # one time per token against another, both as shown (one decimal)
    d = p_ / p0 - 1; a_ = abs(d)
    if a_ < 0.02: return 'same', 'about as fast'
    if d > 0: return 'slower', ('a little slower' if a_ < 0.25 else ('noticeably slower' if a_ < 0.5 else 'much slower'))
    return 'faster', ('a little faster' if a_ < 0.25 else 'noticeably faster')
def long_w(q):                                    # "over four times as long"
    f_ = math.floor(q + 1e-9)
    return ('over ' if q > f_ + 1e-9 else 'about ') + ('twice' if f_ == 2 else f'{NUMW[f_]} times') + ' as long'
