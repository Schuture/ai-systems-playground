import pathlib, json
from playwright.sync_api import sync_playwright
P=pathlib.Path(__file__).resolve().parent.parent
(P/'wrapped.html').write_text('<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0}[hidden]{display:none!important}</style></head><body>'+(P/'ai-systems-playground.html').read_text()+'</body></html>')
URL='file://'+str(P/'wrapped.html'); errs=[]; res=[]
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1440,'height':900})
    pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto(URL+'#_example'); pg.wait_for_timeout(400)
    res.append(('title', pg.inner_text('#view-dyn .labtitle')))
    res.append(('mode desc', pg.evaluate("()=>{const b=document.querySelector('#view-dyn [data-flow-nav] button[aria-pressed=true]'); return b?(b.dataset.tipx||''):''}")))
    pg.click('#view-dyn [data-nav="next"]'); pg.wait_for_timeout(150)
    res.append(('next disabled before change', pg.evaluate("()=>document.querySelector('#view-dyn [data-nav=next]').disabled")))
    pg.evaluate("()=>{const i=document.getElementById('ex-ic-n-in'); i.value=30; i.dispatchEvent(new Event('input',{bubbles:true}))}"); pg.wait_for_timeout(150)
    res.append(('obs + next enabled', pg.inner_text('#view-dyn [data-obs]').replace('\n',' | '), pg.evaluate("()=>document.querySelector('#view-dyn [data-nav=next]').disabled")))
    res.append(('panel synced', pg.evaluate("()=>document.getElementById('ex-ctl-n-in').value")))
    res.append(('hash', pg.evaluate("()=>location.hash")))
    pg.evaluate("()=>document.getElementById('ex-math').open=true"); pg.wait_for_timeout(100)
    pg.hover('#view-dyn .t[data-ctl="p"]'); pg.wait_for_timeout(150); res.append(('term tip', pg.inner_text('#tip').replace('\n',' | ')))
    pg.click('#view-dyn .t[data-ctl="p"]'); pg.wait_for_timeout(700); res.append(('jump focus', pg.evaluate("()=>document.activeElement.closest('#ex-ctl-p')!==null")))
    pg.hover('#ex-status'); pg.wait_for_timeout(120); res.append(('tipx', pg.inner_text('#tip')))
    pg.click('#view-dyn .modes button[data-mode="challenge"]'); pg.wait_for_timeout(150)
    pg.click('#ex-ic-p button[data-v="0.99"]'); pg.click('#view-dyn [data-act="submit"]'); pg.wait_for_timeout(150)
    res.append(('challenge', pg.inner_text('#ex-res').replace('\n',' | ')[:160]))
    pg.click('.langsw button[data-lang="zh"]'); pg.wait_for_timeout(200)
    res.append(('zh title + mode', pg.inner_text('#view-dyn .labtitle'), pg.evaluate("()=>{const b=document.querySelector('#view-dyn [data-flow-nav] button[aria-pressed=true]'); return b?(b.dataset.tipx||''):''}")))
    pg.set_viewport_size({'width':390,'height':700}); pg.wait_for_timeout(200)
    pg.evaluate("()=>document.getElementById('ex-controls').scrollIntoView({block:'center'})"); pg.wait_for_timeout(300)
    res.append(('dock at 390', not pg.evaluate("()=>document.getElementById('dock').hidden"), pg.inner_text('#dock').replace('\n',' ')))
    pg.goto(URL+'#kv-cache'); pg.wait_for_timeout(300); res.append(('kv still works', pg.inner_text('#stStatus')))
    pg.goto(URL+'#map'); pg.wait_for_timeout(300); res.append(('home', pg.evaluate("()=>document.querySelectorAll('#tiles .tile').length")))
    b.close()
for r in res: print(r)
print('errors', errs)
